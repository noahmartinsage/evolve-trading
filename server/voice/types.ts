/** 解析后的下单诉求。金额单位刻意分两类 —— 混淆二者是语音里最容易出人命的一处。 */
export interface OrderSlots {
  side: 'buy' | 'sell'
  symbol: string
  /**
   * 名义额（报价币计价，如 USDT）。
   *
   * 与 `qty` 二选一。**「买两百块钱的比特币」和「买两百个比特币」是两件事**，
   * 前者 200 U，后者在 BTC 上是 1.3 亿 U。ASR 无法区分两者，
   * 只能靠量词判断；量词缺失时本层默认按名义额处理（受逐笔上限约束、
   * 且不随价格漂移），并由两段式确认把解释结果**念回给用户复核**。
   */
  notional?: number
  /** 基础币数量（如 0.01 BTC）。 */
  qty?: number
  /**
   * 数量语义来自哪个量词，用于确认回话里说清"我理解成了什么"。
   *
   * ★ `margin` 这一档是**合约专有**的：中文口语里「10 美金开 125 倍合约」
   *   说的是**保证金**（我出 10 U），不是名义本金（敞口 1250 U）。
   *   两者相差整整一个杠杆倍数，而风控量的是名义本金 ——
   *   把保证金当名义本金，等于只开了用户想要敞口的 1/125，
   *   账面上"成交了"，实际上他把仓位看反了方向。
   *   所以它必须是**独立的一档**，不许并进 `notional`：
   *   现值相同、含义不同，合并之后没有任何断言能把它俩分开。
   */
  amountBasis?: 'notional' | 'qty' | 'margin'

  // ── 以下四组是「合约」相对「现货」多出来的东西 ─────────────────────
  //
  // ★ 为什么这四栏必须先住进 `OrderSlots`：
  //   用户实测原话是「下单 BTC 10 美金 125 倍合约做多，止盈 10 成，止损 1 成」，
  //   而当时的解析层**一个槽位都没有**（`instType` / `leverage` / 止盈 / 止损全缺），
  //   于是这句话被降级成「10 U 现货买入」—— 用户要的是 125 倍合约，
  //   拿到的是 10 块钱现货。**没有任何一道门会报错**，因为那笔单本身完全合法。
  //   这类"合法但完全不是用户要的"错误，只能靠在解析层**把槽位显式装起来**挡住。

  /** 品种形态：缺省 SPOT。用户说了「合约/永续」才是 SWAP。 */
  instType?: 'SPOT' | 'SWAP'
  /** 合约结算方式（仅 SWAP 有意义）：linear = U 本位。 */
  settle?: 'linear' | 'inverse'
  /**
   * 用户**要求**的杠杆倍数。
   *
   * ⚠️ 这不是最终生效值：最终值由 `positionGuard.assertStopBeforeLiquidation()`
   *   按「止损必须先于强平」钳制。两栏分开存，是为了在回话里说清
   *   「你要 125 倍，我按 6 倍下的，原因是止损 10% 时强平只有 0.8%」——
   *   只留一个数的话，用户永远不知道自己被降过杠杆。
   */
  leverage?: number

  /** 止盈幅度（相对入场价）：0.1 = 10%（一成的**价差**）。 */
  takeProfitPct?: number
  /** 止损幅度（相对入场价）：0.1 = 10%。 */
  stopLossPct?: number
  /** 上面两个数各自是从哪段原文听出来的，确认时原样念回，便于用户抓错。 */
  protectionMatched?: { takeProfit?: string; stopLoss?: string }
  /**
   * 用户**提到了**止盈/止损，但比例没解析出来。
   *
   * ★ 单独一栏而不是靠"`takeProfitPct` 为空"推断：两种情况在数值上完全一样
   *   （都是 undefined），含义却相反 —— 一种是用户没提（这是正常的），
   *   一种是用户提了而系统没听懂（这是必须说出来的）。合并之后，
   *   后者会被静默当成前者，用户以为设了保护、实际在裸跑。
   */
  protectionUnparsed?: { takeProfit?: boolean; stopLoss?: boolean }
  /**
   * ★★ 用户**显式放弃**保护价（"不带保护"/"裸单"/"不要止损"）。
   *
   * ── 为什么它必须是**独立一栏**，不能靠"`takeProfitPct` 为空"推断 ────────
   * 「没提到保护」与「明确说不要保护」在数值上完全一样（两个都是空），
   * 而它们指向的动作相反：
   *   没提到 ⇒ 问一句（他可能只是忘了说）；
   *   明确不要 ⇒ 按裸单下，并**如实告诉他这笔单唯一的保护是强平距离**。
   * 合成一栏之后没有任何断言能把两者分开，而这个分歧的方向是
   * **把"忘了说"当成"不要保护"** —— 一次静默降级。
   */
  protectionWaived?: boolean
  /** 命中豁免的原话片段（念回去用："你说的是「不要止损」……"）。 */
  protectionWaiverMatched?: string

  /** 用户是否明确说了"实盘/真钱"。缺省为仿真（paper）。 */
  live?: boolean
  /** 实盘所需的策略身份（必须已过晋升门禁，由流水线层裁决）。 */
  strategyId?: string
}

export interface ParsedIntent {
  intent: VoiceIntentName
  slots?: OrderSlots
  /** 解析置信度 0~1。低置信度一律走确认或直接澄清，不猜。 */
  confidence: number
  /** 命中的原始片段，便于面板展示"我是从哪句里听出来的"。 */
  matched?: string
  voiceId?: string
  verbosity?: Verbosity
  /**
   * 解析过程的显式失败原因（如数量单位不支持、标的缺失）。
   *
   * 为什么要单独一个字段而不是塞进 `matched`：这一层的失败**必须能被念出来**。
   * 「我没听出要买多少」和「我以为是 200 U」对用户是两回事，
   * 压成同一个"没听懂"会让用户反复重说同一句话。
   */
  error?: string
  /** 撤单等按单号操作的意图，把单号单独带出来，不塞进 `slots`。 */
  orderId?: string
  /**
   * 这个标的**是靠上文（指代）才认出来的**，不是用户这句话里说了的。
   *
   * ★ 为什么必须带出去：它是"系统替用户补了一个他没说的东西"。
   *   不声明就等于**猜**，而猜错的代价在下单场景是真实的钱；
   *   声明之后用户才有机会说"我不是说那个"。
   * ★ 判据只有一份 —— 由 `intents.resolveSymbol` 的第 ④ 条产生，
   *   由 `parseIntent` 的包装层统一打标（见那里的注释）。
   */
  resolvedByReference?: boolean
  /**
   * 目标解析结果（仅 `start_mission` 携带）。
   *
   * 由意图层解析一次就带出来，而不是让处理层再解析一遍 ——
   * 解析两次的后果不是性能，是**两处可能给出不同的 spec**：
   * 意图层按 A 判成"是任务"，处理层按 B 判成"缺槽位"，
   * 于是系统会先答应再反问，用户看到的是自相矛盾。
   */
  mission?: MissionSpec
  /**
   * 要登记成心法的原话（仅 `record_lesson` 携带）。
   *
   * ★ 单独一个字段，**不塞进 `slots`**：`slots` 描述的是"一笔交易"，
   * 而这句话描述的是一条经验。塞进去的后果是 `createPending` 会拿它去算
   * `expectedAmount`，于是确认回话里会念出"请确认 0"这种无意义的数字。
   * 语义不同的东西共用一个槽位，受害者永远是确认回话 —— 那是用户唯一能复核的地方。
   */
  lessonText?: string
  /**
   * 要交给舰队办的原话（仅 `dispatch_task` 携带）。
   *
   * ★ 与 `lessonText` 同一条理由：语义不同的东西不共用槽位。
   *   更要紧的是这里**必须带原话而不是解析结果** —— 能不能接、按哪条链走
   *   由舰队的 `planTask()` 决定，它是唯一的口径。语音层若自己解析一次
   *   再传下去，就会出现"语音层说能听懂、舰队说听不懂"这种两套口径。
   */
  taskGoal?: string
  /**
   * 要联网查的词（仅 `web_lookup` 携带）。
   *
   * 与 `taskGoal` 分开，是因为去向完全不同：一个进舰队调度器（会改系统），
   * 一个进受控出网（只读）。共用一个字段的后果是两条路径的审计事件里
   * 出现同名不同义的参数 —— 事后没人能分辨那次出网是不是舰队干的。
   */
  webQuery?: string
  /**
   * 要预测的标的（仅 `query_forecast` 携带）。
   *
   * ★ 缺省是 `undefined` 而**不是** `'BTCUSDT'`：调用方没说是哪个币的时候，
   *   系统必须**问一句**，不许自己挑一个顶上 —— 挑错的后果是把"以太坊的预测"
   *   当成"比特币的预测"讲出来，而那句话在字面上完全说得通。
   *   （与 `resolveSymbol` 命中不了就返回 null 是同一条纪律。）
   */
  forecastSymbol?: string
  /**
   * 预测的时间跨度（分钟，仅 `query_forecast` 携带）。
   *
   * ★ 存**分钟**而不是"根数"：用户说的是"未来一小时"，而"一小时是多少根"
   *   取决于 bar 分辨率 —— 那个决定属于预测层（它知道只有 15m 一档证据），
   *   不属于语音层。语音层只负责把"一小时"听懂成 `60`。
   */
  horizonMinutes?: number
}

/**
 * 播报档位。
 *
 * ★ `normal` 的定义在 2026-09-17 改过一次，起因是一个**功能性失效**：
 * 它原本只放行 P0/P1，而「我正在干什么、下一步干什么」是 **P2_STATUS** ——
 * 后端一直在生成这些句子（`tickStatus` 由 3 秒一次的泵驱动），
 * 默认档位却把它们**整批丢掉**。用户的体感就是"它一点都不智能、从不报告在做什么"。
 *
 * 这不是缺功能，是**缺功能的可见性**：一份永远不会被消费的输出，
 * 和没写这段代码没有区别（本项目反复出现的"算而不用"，这里又是一次）。
 *
 * 分层按"离钱的距离"排，而不是按"实现顺序"排：
 *   · alarm-only —— 只 P0。盯盘时不想被打扰。
 *   · normal（默认）—— P0/P1/P2，含工作状态与下一步。**桌宠的默认人格**。
 *   · chatty —— 全部，再加 P3 盘面异动与闲聊。
 */
export type Verbosity =
  /** 只说报警。连成交都不播 —— 适合盯盘时不想被打扰。 */
  | 'alarm-only'
  /** 报警 + 重要事件 + **工作状态与下一步**。 */
  | 'normal'
  /** 全部，含盘面异动明细与闲聊。 */
  | 'chatty'

/**
 * 两段式确认凭证。
 *
 * 语音没有"撤销"，所以任何**会改变资金状态**的动作都必须先拿到这个东西。
 * 关键设计：确认不是简单回一句「确认」——
 * 那样一句含糊的"确认"就能放行，而含糊正是 ASR 的常态。
 * 这里要求用户**把解释后的数量复述一遍**（「确认两百」），
 * 于是确认动作同时完成两件事：授权 + 校验识别是否听错。
 */
export interface PendingConfirmation {
  token: string
  ts: number
  expiresAt: number
  /**
   * 待执行动作的**机器标识**。
   *
   * 刻意与下面的 `action`（给人看的描述）分开，且路由只认这一个。
   * 曾经想过「用 action 字符串前缀判断该走哪条分支」——那等于让展示文案
   * 承担路由职责：改一个中文字就不分叉了，而且编译器一声不吭。
   */
  intent: VoiceIntentName
  /** 给人看的动作描述，用于回话与面板。改它不会改变行为。 */
  action: string
  /** 必须被复述出来的数值（名义额 / 数量 / 合约保证金）。用户念别的数一律不放行。 */
  expectedAmount: number
  /**
   * 这个数是什么单位。
   *
   * ★ 与 `OrderSlots.amountBasis` 同一套取值，含 `margin` ——
   *   合约单里用户念回来的那个数是**保证金**，不是名义额。
   *   少了这一档，确认回话会拿名义额去核对用户念的保证金，
   *   两个数差一个杠杆倍数 ⇒ 规范操作反而永远确认不过去。
   */
  amountBasis: 'notional' | 'qty' | 'margin'
  /**
   * 合约单的**第二个可接受复述值**：名义额。
   *
   * ★ 为什么契约单需要它：用户说「10 美金 125 倍合约」，他心里那个数是 10
   *   （保证金），而系统量的风险是 1250（名义额）。两个都是**他自己给过的数**，
   *   只认一个的后果是：规范操作会被念成"你念的不对"，因为他念的是自己刚说的那个。
   *   （判据 2：会不会对**正确的**输入报错。）
   *
   * ★ 它不削弱校验：两个值都由服务端从同一条请求推出，
   *   ASR 听错要恰好命中另一个值，等于要在同一句话里听错两次。
   */
  expectedAmountAlt?: number
  /**
   * 服务端按实时标记价折算出的名义额。
   *
   * 存在的意义：风险分档必须量**钱**，不能量"用户嘴里那个数"。
   * 「买一个比特币」里 qty=1 看着无害，实际名义额十万量级 ——
   * 只按 qty 分档的话这笔会被判成小额单而免去复核。
   */
  expectedNotional: number
  /** 已解析好、确认后原样转交的槽位。 */
  slots: OrderSlots
  /** 触发它的轮次，便于把「确认」关联回上下文。 */
  originTurnId: number
  /**
   * 非订单类动作的**文字参数**（目前只有 `record_lesson` 的心法正文）。
   *
   * ★ 为什么不塞进 `slots`：`slots` 描述的是一笔交易，`createPending` 会拿它
   * 去算 `expectedAmount`，于是确认回话里会念出"请确认 0"这种没有含义的数字 ——
   * 而确认回话是用户唯一能复核的地方，那里的每个数字都必须有含义。
   * 心法正文与"多少钱"是两种东西，各占各的字段。
   */
  intentArg?: string
  /**
   * 待确认的**界面按钮 id**（见 `server/uiActions.ts` 的 `UI_ACTIONS`）。
   *
   * ★ 与 `intentArg` 同源的理由，也是刻意不塞进 `slots`：
   *   `slots` 描述的是一笔交易，`createPending` 会拿它去算 `expectedAmount`，
   *   于是确认回话会变成"请复述金额 0" —— 用户在复核一个没有含义的数字。
   *   "按哪颗按钮"与"下多少钱"是两种东西。
   *
   * ★ 它存在时的语义：确认后**不是**走 `dispatchDangerous`，
   *   而是把这条动作排进界面队列，由界面自己去点那颗按钮。
   *   也就是说"确认"这一步校验的是**人有没有批准**，
   *   而真正动手的仍然是界面上那颗按钮的同一个人 onClick。
   */
  uiActionId?: string
  /** 待确认按钮在屏幕上的那张脸（回话要用它，免得用户对不上号）。 */
  uiActionLabel?: string
}

/** 语音层对外暴露的状态快照（给面板与烟测）。 */
export interface VoiceStatus {
  enabled: boolean
  voiceId: string
  verbosity: Verbosity
  /** 当前轮次。 */
  turn: VoiceTurn | null
  /** 世代号：每发生一次打断就 +1，用于作废在途回话。 */
  generation: number
  interruptedCount: number
  spokenCount: number
  suppressedCount: number
  pending: PendingConfirmation | null
  recentNarrations: NarrationLine[]
}
