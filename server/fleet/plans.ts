/**
 * 舰队任务计划表 —— 「一句话能不能接、接了就干什么」的**唯一口径**
 *
 * ── 为什么把它从 service.ts 抽出来 ──────────────────────────────────
 * 这块逻辑原本住在 `service.ts` 里，而 `voice/intents.ts` 要判"这句话是不是派活"
 * 就必须 import 整个 service（连带 autopilot / factorService / pipelineService…）。
 * 于是语音层**绕开了它、自己写了一份硬编码白名单**。实测的后果很具体：
 *   · 「检查文件是否有用」—— 舰队层能接（hygiene 计划），语音层却回"没听懂"；
 *   · 「没有用的垃圾及时清洗」—— 同上。
 * 用户看到的是"它明明能做这件事，却说不会"，而这正是判据 8 说的
 * "同一个业务动作有两条实现路径，两条迟早给出不同答案"。
 *
 * 抽出来之后依赖变轻：本模块只认字符串与结构，不 import 任何执行侧模块。
 * 于是"能听懂什么"只有一份，语音层与 HTTP 层**调的是同一个函数**。
 *
 * ── `writes` 这个字段是干什么的 ──────────────────────────────────────
 * 它标"这个计划会不会改变系统状态"。它唯一的用途是：**疑问句不许被当成派活**。
 *   · 「系统巡检」      —— 动作，跑（`writes: false`，只读）
 *   · 「舰队现在怎么样」—— 提问，**不跑**（`writes: false` 也允许跑，但语义是"去查一遍"）
 *   · 「跑一轮提案」    —— 动作，跑（`writes: true`）
 *   · 「提案跑得怎么样」—— 提问，**不跑**（`writes: true` + 疑问 ⇒ 拒绝）
 * 这一条能挡住的是本项目最贵的一类错误之一：**用户问了一句，系统写了一笔**。
 */

export interface TaskPlan {
  id: string
  label: string
  patterns: RegExp[]
  /** 链上的成员，按执行顺序。 */
  chain: string[]
  why: string
  /** 会不会改变系统状态（写台账 / 移文件 / 落提案）。疑问句下 `true` 的计划不被承接。 */
  writes: boolean
  /**
   * ★ **撤销这件事的计划 id** —— 有值即"可逆"，且指名了**谁能退**。
   *
   * ── 为什么不是 `reversible: boolean` ────────────────────────────────
   * 布尔是**自报**：谁都能填 `true`，而没有任何东西能核对它。
   * 本仓库为此付过代价（凭据只许装可观测量、不许装结论）。
   * 写成"撤销我的是谁"就变成**指针**，于是门禁可以断言：
   *   ① 它指向的计划真的存在；
   *   ② 那个计划真的在反向执行（不是随便指一个无辜的计划）。
   * 这两条**只有它**能作为证据（判据 3）。
   *
   * ── 它唯一的用途：免二次确认 ──────────────────────────────────────
   * 见 `planNeedsConfirm()`。理由与判据 29 同源：用户已经把这件事
   * **点名说了出来**（命中了本计划的模式），再问一遍"要不要做"
   * 就是让用户确认自己的明确指令 —— 用户实测的原话正是
   * 「说『启动自治循环』总览那颗按钮还是没变成『停止』」，
   * 因为他不知道还得再说一句「确认」。
   *
   * 而"不可逆动作必须先问"这条之所以成立，靠的是**做错了退不回来**。
   * 能原样退回来的动作不需要预授权 —— 它需要的是**撤回路径是通的**，
   * 这正是本字段要证明的东西。
   *
   * ★ 真钱模式（live）**一律照问**，哪怕它有 `undoPlan`：
   *   `undoPlan` 能撤销的是**系统状态**，撤销不了**已经打到场所的订单**。
   *   所以这条判定在服务端现读模式，**不接受调用方自报"我是纸面"**。
   */
  undoPlan?: string
}

