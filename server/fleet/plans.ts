export interface PlanResult {
  plan: TaskPlan | null
  why: string
}

/**
 * 这句话在**问**还是在**做**。
 *
 * ★ 它只用来挡一件事：`writes: true` 的计划遇到疑问句时不承接。
 *   不是"疑问句一律不接" —— 只读计划（巡检 / 决策质量 / 心法健康）在疑问句下
 *   照样接，因为"问我现在的状态"和"去查一遍"本来就是同一件事。
 */
export function looksInterrogative(s: string): boolean {
  // ★ `能干什么 / 能做什么 / 干什么用 / 有什么用` 这一族是**实测补上的**：
  //   它们是最典型的"问能力"句式，却不含 `吗/呢/哪些/怎么样` 里任何一个字
  //   ⇒ 「进化实验室能干什么」被判成"不是疑问句"，于是被 `writes: true` 的 `propose`
  //   计划认领成一次"跑一轮提案"。用户问一句、系统写一笔，正是这条判据要挡的事。
  //   （`help` 意图在语音层更靠前，所以「你能干什么」不受影响。）
  //
  // ★ `解释 / 什么是 / 是什么意思` 这一族是**界面动作通道接进来时**补的，
  //   同样是一次"问一句、系统动一下"：那一层只认"动作词 + 按钮名"，
  //   而「帮我解释一下什么是启动」同时含「帮我」与「启动」（系统监控页那颗按钮）
  //   ⇒ 被判成"要按按钮"。原有那套词一个都不命中（它只有「什么样」，没有「什么」），
  //   所以这里补的是**求解释**这一族，而不是把「什么」放开
  //   —— 放开「什么」会把「跑一轮提案什么结果」这类命令也误判成提问。
  return /(什么样|怎么样|怎么回|如何|多少|几个|几条|哪些|哪个|了吗|了没|吗|呢|能干什么|能做什么|干什么用|是干什么的|有什么用|解释|说明一下|介绍一下|是什么意思|什么是|是啥|啥意思|干嘛|干吗|？|\?)/.test(
    s,
  )
}

/** 把一句话映射成成员链。判不出来就返回 null —— **不猜**，并列出能听懂的说法。 */
export function planTask(goal: string): PlanResult {
  const g = goal.trim()
  if (g.length === 0) return { plan: null, why: '目标为空' }
  const hits = FLEET_TASK_PLANS.filter((p) => p.patterns.some((re) => re.test(g)))
  if (hits.length === 0) {
    return {
      plan: null,
      why: `没听懂「${g}」。我能接的说法有：${FLEET_TASK_PLANS.map((p) => p.label).join('、')}。`,
    }
  }
  // 疑问句：只读计划照接，会写东西的计划**不接**（用户问了一句，不该被写成一笔）。
  const readOnly = hits.find((p) => !p.writes)
  if (looksInterrogative(g)) {
    if (readOnly) return { plan: readOnly, why: readOnly.why }
    const blocked = hits[0]
    return {
      plan: null,
      why:
        `「${g}」听起来是在**问**「${blocked.label}」的结果，而不是让我去做。` +
        '所以我没动 —— 你要真让我跑，去掉疑问词再说一次（比如「扩候选基因空间」）。',
    }
  }
  const hit = hits[0]
  return { plan: hit, why: hit.why }
}

/** 供语音层列出"我能接哪些说法"。 */
export function planLabelList(): string {
  return FLEET_TASK_PLANS.map((p) => p.label).join('、')
}

/**
 * ★★ 这一句话要不要**先问人**。
 *
 * 这是"一句话而已，怎么还要我确认两遍"这个体验问题的**唯一裁决点**。
 * 它的取舍写在 `TaskPlan.undoPlan` 的注释里，这里只说清边界：
 *
 *   · 只读计划（`writes: false`）        ⇒ **不问**（它改不了任何东西）
 *   · 会写东西、且**没指名撤销计划**     ⇒ **问**（退不回来，必须先授权）
 *   · 会写东西、且指名了撤销计划 + 纸面  ⇒ **不问**（能原样退回去）
 *   · 会写东西、指名了撤销计划但**是实盘** ⇒ **问**
 *     （撤销计划能退回系统状态，退不回已经打到场所的单）
 *
 * ── 为什么把 `paperOnly` 做成入参而不是在这里现读 ────────────────────
 * `plans.ts` 刻意不 import 任何执行侧模块（见文件头），这样语音层与 HTTP
 * 层才能共用同一张表而不把 `autopilot` 拖进来。模式由**调用方现读**
 * `autopilotStatus().mode` —— 那是全系统唯一的模式口径，
 * 于是"这里以为的纸面"与"执行时以为的纸面"在结构上不可能分岔。
 * 门禁因此可以同时断言它的两个方向（判据 5：可注入才验得了"不过"）。
 *
 * ★ 注意这里**不是**"用户说了就直接干"：命中计划本身就是"用户点名
 *   说出了这件事"的证据（`planTask` 只按明确的动作说法匹配）。
 *   没命中计划的原话走的是澄清，压根到不了这里。
 */
export function planNeedsConfirm(plan: TaskPlan, paperOnly: boolean): boolean {
  if (!plan.writes) return false
  if (!plan.undoPlan) return true
  return !paperOnly
}

/**
 * 撤销某个计划的计划是哪一个。
 *
 * **返回 null 的含义要写清楚**：它是"本表里没有任何计划声明能撤销它"，
 * 而不是"这件事没法撤销"。两者在当前实现里等价，但话不能混着说 ——
 * 判据 24 的形态（不许把"我这没有"说成"世上没有"）。
 */
export function undoPlanOf(plan: TaskPlan): TaskPlan | null {
  if (!plan.undoPlan) return null
  return FLEET_TASK_PLANS.find((p) => p.id === plan.undoPlan) ?? null
}
